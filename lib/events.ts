/*
  Cheer Pressure messages: the shared event types and their validators.

  The only data that ever goes to the messages service is what is defined here: short
  greetings, questions, replies and contact requests between the person and one trusted
  person. Never sensor data, measurements, check-in answers or anything about health.

  No dependencies and no imports, so the same file works in the desktop app and in the
  messages service. `server/lib/events.ts` is a byte-for-byte copy of this file
  (scripts/test-messages.mts checks that they are identical). Edit this one, then copy it.
*/

export const EVENT_VERSION = 1 as const;
export const TEXT_MAX = 280;
export const NAME_MAX = 40;

/** Pair codes: 6 characters from an alphabet without 0/O, 1/I/L. */
export const PAIR_ALPHABET = "23456789ABCDEFGHJKMNPQRSTUVWXYZ";
export const PAIR_LENGTH = 6;

export type Role = "user" | "trusted";
export type EventType = "greeting" | "reply" | "contact_request";
export type Answer = "yes" | "no";

interface EventBase {
  v: typeof EVENT_VERSION;
  type: EventType;
  /** Assigned by the server. */
  id: string;
  /** Assigned by the server, ISO 8601. */
  ts: string;
  pair: string;
  /** Generated by the sending device, so a retried send never creates a second event. */
  clientId: string;
}

export interface GreetingEvent extends EventBase {
  type: "greeting";
  from: { role: "trusted"; name: string };
  text: string;
  kind: "greeting" | "question";
  replyTo: null;
}

export interface ReplyEvent extends EventBase {
  type: "reply";
  from: { role: Role };
  replyTo: string;
  answer: Answer | null;
  text: string;
}

export interface ContactRequestEvent extends EventBase {
  type: "contact_request";
  from: { role: "user" };
  text: string;
}

export type MessageEvent = GreetingEvent | ReplyEvent | ContactRequestEvent;

/** What a device sends. The server adds v, id, ts, pair and from. */
export type GreetingDraft = { type: "greeting"; clientId: string; text: string; kind: "greeting" | "question" };
export type ReplyDraft = { type: "reply"; clientId: string; replyTo: string; answer: Answer | null; text: string };
export type ContactRequestDraft = { type: "contact_request"; clientId: string; text: string };
export type EventDraft = GreetingDraft | ReplyDraft | ContactRequestDraft;

export type Result<T> = { ok: true; value: T } | { ok: false; error: string };

const ok = <T>(value: T): Result<T> => ({ ok: true, value });
const fail = <T>(error: string): Result<T> => ({ ok: false, error });

// Control characters other than line feed and tab are refused.
const CONTROL = /[\u0000-\u0008\u000B-\u001F\u007F]/;

/** Length in characters as a person counts them (code points, so an emoji is one). */
export function charLength(s: string): number {
  return Array.from(s).length;
}

/** Trims, then checks 1 to max characters and no control characters. */
export function checkText(value: unknown, max = TEXT_MAX, field = "text"): Result<string> {
  if (typeof value !== "string") return fail(`${field} must be a string`);
  const s = value.trim();
  const n = charLength(s);
  if (n < 1) return fail(`${field} is empty`);
  if (n > max) return fail(`${field} is longer than ${max} characters`);
  if (CONTROL.test(s)) return fail(`${field} contains control characters`);
  return ok(s);
}

export function checkName(value: unknown): Result<string> {
  const r = checkText(value, NAME_MAX, "name");
  if (!r.ok) return r;
  if (/[\r\n\t]/.test(r.value)) return fail("name must be one line");
  return r;
}

export const isValidText = (value: unknown): boolean => checkText(value).ok;
export const isValidName = (value: unknown): boolean => checkName(value).ok;

const ID_RE = /^[A-Za-z0-9_-]{8,64}$/;
export const isValidId = (value: unknown): value is string => typeof value === "string" && ID_RE.test(value);

export function isValidPair(value: unknown): value is string {
  if (typeof value !== "string" || value.length !== PAIR_LENGTH) return false;
  for (const c of value) if (!PAIR_ALPHABET.includes(c)) return false;
  return true;
}

/** Which role may send which event type. */
export function canSend(role: Role, type: EventType): boolean {
  if (type === "greeting") return role === "trusted";
  if (type === "contact_request") return role === "user";
  return type === "reply";
}

const isObject = (x: unknown): x is Record<string, unknown> => typeof x === "object" && x !== null && !Array.isArray(x);

/** Checks what a device wants to send. Does not check the role: use canSend for that. */
export function parseDraft(input: unknown): Result<EventDraft> {
  if (!isObject(input)) return fail("body must be a JSON object");
  if (!isValidId(input.clientId)) return fail("clientId must be 8 to 64 letters, digits, - or _");
  const clientId = input.clientId;
  const text = checkText(input.text);
  switch (input.type) {
    case "greeting": {
      if (!text.ok) return fail(text.error);
      if (input.kind !== "greeting" && input.kind !== "question") return fail("kind must be greeting or question");
      if (input.replyTo !== undefined && input.replyTo !== null) return fail("a greeting has no replyTo");
      return ok({ type: "greeting", clientId, text: text.value, kind: input.kind });
    }
    case "reply": {
      if (!text.ok) return fail(text.error);
      if (!isValidId(input.replyTo)) return fail("replyTo must be an event id");
      const answer = input.answer ?? null;
      if (answer !== null && answer !== "yes" && answer !== "no") return fail("answer must be yes, no or null");
      return ok({ type: "reply", clientId, replyTo: input.replyTo, answer, text: text.value });
    }
    case "contact_request": {
      if (!text.ok) return fail(text.error);
      return ok({ type: "contact_request", clientId, text: text.value });
    }
    default:
      return fail("type must be greeting, reply or contact_request");
  }
}

/** Checks a complete event, for example one received from the service or read from a cache. */
export function validateEvent(input: unknown): Result<MessageEvent> {
  if (!isObject(input)) return fail("event must be an object");
  if (input.v !== EVENT_VERSION) return fail("unknown event version");
  if (!isValidId(input.id)) return fail("bad id");
  if (typeof input.ts !== "string" || Number.isNaN(Date.parse(input.ts))) return fail("bad ts");
  if (!isValidPair(input.pair)) return fail("bad pair");
  const draft = parseDraft(input);
  if (!draft.ok) return fail(draft.error);
  const from = input.from;
  if (!isObject(from)) return fail("bad from");
  const base = { v: EVENT_VERSION, id: input.id, ts: input.ts, pair: input.pair, clientId: draft.value.clientId };
  const d = draft.value;
  if (d.type === "greeting") {
    if (from.role !== "trusted") return fail("a greeting comes from the trusted person");
    const name = checkName(from.name);
    if (!name.ok) return fail(name.error);
    return ok({ ...base, type: "greeting", from: { role: "trusted", name: name.value }, text: d.text, kind: d.kind, replyTo: null });
  }
  if (d.type === "reply") {
    if (from.role !== "user" && from.role !== "trusted") return fail("bad from.role");
    return ok({ ...base, type: "reply", from: { role: from.role }, replyTo: d.replyTo, answer: d.answer, text: d.text });
  }
  if (from.role !== "user") return fail("a contact request comes from the person");
  return ok({ ...base, type: "contact_request", from: { role: "user" }, text: d.text });
}

/** A random id usable as clientId, without relying on crypto.randomUUID (missing on plain http). */
export function newClientId(): string {
  const c = (globalThis as { crypto?: Crypto }).crypto;
  if (c && typeof c.randomUUID === "function") {
    try {
      return c.randomUUID();
    } catch {
      // randomUUID throws outside a secure context in some browsers; fall through.
    }
  }
  const bytes = new Uint8Array(16);
  if (c && typeof c.getRandomValues === "function") c.getRandomValues(bytes);
  else for (let i = 0; i < 16; i++) bytes[i] = Math.floor(Math.random() * 256);
  bytes[6] = (bytes[6] & 0x0f) | 0x40;
  bytes[8] = (bytes[8] & 0x3f) | 0x80;
  const hex = Array.from(bytes, (b) => b.toString(16).padStart(2, "0")).join("");
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}
